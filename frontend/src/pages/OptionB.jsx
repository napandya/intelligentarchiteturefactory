function ScrollyShot({ layer, index }) {
  const ref = useRef(null);
  const reduce = useReducedMotion();
  const { scrollYProgress } = useScroll({ target: ref, offset: ["start end", "end start"] });
  const y = useTransform(scrollYProgress, [0, 1], reduce ? [0, 0] : [40, -40]);
  return (
    <div ref={ref} className={`grid items-center gap-10 py-16 lg:grid-cols-2 ${index % 2 ? "lg:[&>*:first-child]:order-2" : ""}`}>
      <Reveal>
        <p className="font-mono text-[11px] uppercase tracking-[0.24em] text-[var(--electric)]">{layer.label}</p>
        <p className="mt-3 font-display text-2xl font-semibold text-[var(--ink)] sm:text-3xl">{layer.caption.split("—")[0]}</p>
        <p className="mt-2 font-mono text-[11px] uppercase tracking-[0.18em] text-[var(--muted)]">{layer.caption.split("—")[1]}</p>
      </Reveal>
      <motion.figure style={{ y }} className="border border-[var(--line-strong)]">
        <div className="flex items-center gap-2 border-b border-[var(--line)] bg-[var(--surface)] px-4 py-2.5">
          <span className="h-2 w-2 rounded-full bg-[var(--line-strong)]" aria-hidden="true" />
          <span className="h-2 w-2 rounded-full bg-[var(--line-strong)]" aria-hidden="true" />
          <span className="h-2 w-2 rounded-full bg-[var(--electric)]" aria-hidden="true" />
          <span className="ml-3 font-mono text-[10px] uppercase tracking-[0.18em] text-[var(--muted)]">iaf / workspace</span>
        </div>
        <img
          src={layer.src}
          alt={layer.caption.charAt(0) + layer.caption.slice(1).toLowerCase()}
          className="w-full"
          loading="lazy"
        />
      </motion.figure>
    </div>
  );
}

